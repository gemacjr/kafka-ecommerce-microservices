package com.kafkademo.notification.controller;

import com.kafkademo.notification.model.Notification;
import com.kafkademo.notification.service.NotificationService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.media.ArraySchema;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import java.util.List;

@RestController
@RequestMapping("/api/notifications")
@Tag(name = "Notifications", description = "Read notifications generated by Kafka events. Notifications are written when payments.processed and inventory.reserved events are consumed.")
public class NotificationController {

    private final NotificationService notificationService;

    public NotificationController(NotificationService notificationService) {
        this.notificationService = notificationService;
    }

    @Operation(
        summary = "Get all notifications",
        description = "Returns all notifications logged from Kafka events. " +
                      "Each entry corresponds to a PAYMENT_SUCCESS, PAYMENT_FAILED, STOCK_RESERVED, or STOCK_INSUFFICIENT event. " +
                      "Polled by the frontend dashboard every 2 seconds to drive the live event log and flow diagram animations.",
        responses = {
            @ApiResponse(responseCode = "200", description = "List of notifications",
                content = @Content(array = @ArraySchema(schema = @Schema(implementation = Notification.class)))),
        }
    )
    @GetMapping
    public ResponseEntity<List<Notification>> getNotifications() {
        List<Notification> notifications = notificationService.getRecentNotifications();
        return ResponseEntity.ok(notifications);
    }
}
